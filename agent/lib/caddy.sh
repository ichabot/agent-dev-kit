#!/usr/bin/env bash
# Caddy pieces shared by agent/render-services.sh (agent VPS) and test/render-services.sh (TEST
# VM). Requires versions.sh sourced. Pure functions: they print text, nothing else.

# adk_caddy_dockerfile GENERATOR PROVIDER: Dockerfile of Caddy with the pinned caddy-dns module
# of PROVIDER (stdout); returns 1 with a message if PROVIDER has no pinned module
adk_caddy_dockerfile() {
  local generator="$1" provider="$2" module
  module="${ADK_CADDY_DNS_MODULES[$provider]:-}"
  if [[ -z "$module" ]]; then
    echo "ERROR: DNS_PROVIDER '$provider' has no pinned caddy-dns module in agent/lib/versions.sh" \
      "(supported: ${!ADK_CADDY_DNS_MODULES[*]}); add it there or use ACME_MODE=http01" >&2
    return 1
  fi
  printf '%s\n' "# Generated by $generator - Caddy with the caddy-dns module for $provider.
FROM $ADK_CADDY_BUILDER_IMAGE AS builder
RUN xcaddy build v$ADK_CADDY_VERSION --with $module

FROM $ADK_CADDY_IMAGE
COPY --from=builder /usr/bin/caddy /usr/bin/caddy"
}

# adk_caddy_image GENERATOR MODE PROVIDER: image name for compose (dns01: tag from the
# Dockerfile's hash, built locally; http01: the pinned stock image)
adk_caddy_image() {
  local hash
  if [[ "$2" == dns01 ]]; then
    hash="$(adk_caddy_dockerfile "$1" "$3" | sha256sum | cut -c1-12)"
    printf 'adk/caddy-%s:%s-%s\n' "$3" "$ADK_CADDY_VERSION" "$hash"
  else
    printf '%s\n' "$ADK_CADDY_IMAGE"
  fi
}

# adk_caddy_options ADMIN_COMMENT ADMIN_VALUE EMAIL MODE PROVIDER TLS_INTERNAL: the global
# options block (admin endpoint, ACME account, DNS-01 with the token from the environment
# unless TLS_INTERNAL, HTTP/1.1 + HTTP/2 only)
adk_caddy_options() {
  local syntax
  echo "{"
  echo "	# $1"
  echo "	admin $2"
  echo "	email $3"
  if [[ "$4" == dns01 && -z "$6" ]]; then
    syntax="${ADK_CADDY_DNS_TOKEN_SYNTAX[$5]:-arg}"
    if [[ "$syntax" == arg ]]; then
      echo "	acme_dns $5 {env.DNS_API_TOKEN}"
    else
      echo "	acme_dns $5 {"
      echo "		$syntax {env.DNS_API_TOKEN}"
      echo "	}"
    fi
  fi
  echo "	servers {"
  echo "		# HTTP/3 needs udp/443, which the Hetzner firewall does not open."
  echo "		protocols h1 h2"
  echo "	}"
  echo "}"
}

# adk_caddy_headers: the security header block of every site (one tab indented)
adk_caddy_headers() {
  echo "	header {"
  echo "		defer"
  echo "		Strict-Transport-Security \"max-age=31536000\""
  echo "		X-Content-Type-Options \"nosniff\""
  echo "		X-Frame-Options \"DENY\""
  echo "		Referrer-Policy \"strict-origin-when-cross-origin\""
  echo "		-Server"
  echo "	}"
}
