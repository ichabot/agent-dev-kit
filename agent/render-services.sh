#!/usr/bin/env bash
# Render the service configuration of the agent VPS from kit.env into a directory:
#
#   compose.yaml      Gitea + Caddy (root Docker, project "adk"); Gitea has no host port
#   Caddyfile         TLS (ACME DNS-01 or HTTP-01), security headers, admin API off
#   caddy/Dockerfile  only for ACME_MODE=dns01: Caddy with the pinned caddy-dns module
#   runner.yaml       Gitea runner config (rootless Docker of user ci)
#
# Usage: agent/render-services.sh --config FILE --out DIR [--gitea-uid UID] [--gitea-gid GID]
#
#   --gitea-uid/--gitea-gid  host uid/gid the Gitea container runs as (setup.sh: system
#                            user adk-gitea; default 1000, the image's own default)
#
# Lab/test overrides (environment only, deliberately NOT kit.env keys):
#   ADK_TLS_INTERNAL=1         Caddy uses its internal CA ("tls internal") instead of ACME;
#                              job containers get the host's CA bundle mounted read-only
#   ADK_RUNNER_ADD_HOST=<ip>   job containers resolve GITEA_DOMAIN to <ip> (no public DNS)
#
# Secrets are never rendered: compose.yaml only references files in /opt/adk/secrets.
# Exit codes: 0 = rendered, 1 = invalid kit.env / unsupported value, 2 = usage.
set -euo pipefail
export LC_ALL=C

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
# shellcheck source-path=SCRIPTDIR source=../scripts/lib/config.sh
source "$ROOT/scripts/lib/config.sh"
# shellcheck source-path=SCRIPTDIR source=lib/versions.sh
source "$HERE/lib/versions.sh"

SECRETS_DIR=/opt/adk/secrets
GITEA_DATA=/var/lib/adk/gitea
RUNNER_STATE=/var/lib/adk-runner

usage() { echo "usage: $0 --config FILE --out DIR [--gitea-uid UID] [--gitea-gid GID]" >&2; exit 2; }

CONFIG="" OUT="" GITEA_UID=1000 GITEA_GID=1000
while (($#)); do
  case "$1" in
    --config) (($# >= 2)) || usage; CONFIG="$2"; shift 2 ;;
    --out) (($# >= 2)) || usage; OUT="$2"; shift 2 ;;
    --gitea-uid) (($# >= 2)) || usage; GITEA_UID="$2"; shift 2 ;;
    --gitea-gid) (($# >= 2)) || usage; GITEA_GID="$2"; shift 2 ;;
    *) usage ;;
  esac
done
[[ -n "$CONFIG" && -n "$OUT" ]] || usage
[[ "$GITEA_UID" =~ ^[1-9][0-9]{0,8}$ && "$GITEA_GID" =~ ^[1-9][0-9]{0,8}$ ]] \
  || { echo "ERROR: --gitea-uid/--gitea-gid must be non-root ids" >&2; exit 2; }
[[ -d "$OUT" ]] || { echo "ERROR: output directory $OUT does not exist" >&2; exit 2; }

TLS_INTERNAL="${ADK_TLS_INTERNAL:-}"
[[ -z "$TLS_INTERNAL" || "$TLS_INTERNAL" == 1 ]] \
  || { echo "ERROR: ADK_TLS_INTERNAL must be 1 or empty" >&2; exit 2; }
ADD_HOST="${ADK_RUNNER_ADD_HOST:-}"
if [[ -n "$ADD_HOST" ]] && ! python3 -I -c 'import ipaddress, sys; ipaddress.ip_address(sys.argv[1])' "$ADD_HOST" 2>/dev/null; then
  echo "ERROR: ADK_RUNNER_ADD_HOST must be a single IP address" >&2
  exit 2
fi

if ! check_out="$("$ROOT/scripts/check-config.sh" "$CONFIG")"; then
  printf '%s\n' "$check_out" >&2
  exit 1
fi
load_config "$CONFIG"
DOMAIN="${CFG[GITEA_DOMAIN]}"
MODE="${CFG[ACME_MODE]}"
PROVIDER="${CFG[DNS_PROVIDER]}"
EMAIL="${CFG[ACME_EMAIL]}"

# --- Caddy image -----------------------------------------------------------------------
caddy_build=false
if [[ "$MODE" == dns01 ]]; then
  module="${ADK_CADDY_DNS_MODULES[$PROVIDER]:-}"
  if [[ -z "$module" ]]; then
    echo "ERROR: DNS_PROVIDER '$PROVIDER' has no pinned caddy-dns module in agent/lib/versions.sh" \
      "(supported: ${!ADK_CADDY_DNS_MODULES[*]}); add it there or use ACME_MODE=http01" >&2
    exit 1
  fi
  dockerfile="# Generated by agent/render-services.sh - Caddy with the caddy-dns module for $PROVIDER.
FROM $ADK_CADDY_BUILDER_IMAGE AS builder
RUN xcaddy build v$ADK_CADDY_VERSION --with $module

FROM $ADK_CADDY_IMAGE
COPY --from=builder /usr/bin/caddy /usr/bin/caddy"
  mkdir -p "$OUT/caddy"
  printf '%s\n' "$dockerfile" > "$OUT/caddy/Dockerfile"
  hash="$(printf '%s\n' "$dockerfile" | sha256sum | cut -c1-12)"
  caddy_image="adk/caddy-$PROVIDER:$ADK_CADDY_VERSION-$hash"
  caddy_build=true
else
  rm -rf "$OUT/caddy"
  caddy_image="$ADK_CADDY_IMAGE"
fi

# --- Caddyfile -------------------------------------------------------------------------
{
  echo "# Generated by agent/render-services.sh from kit.env - do not edit, re-run setup.sh."
  echo "{"
  echo "	# No admin endpoint (:2019): sshd lets hermes tunnel to any loopback port."
  echo "	admin off"
  echo "	email $EMAIL"
  if [[ "$MODE" == dns01 && -z "$TLS_INTERNAL" ]]; then
    echo "	acme_dns $PROVIDER {env.DNS_API_TOKEN}"
  fi
  echo "	servers {"
  echo "		# HTTP/3 needs udp/443, which the Hetzner firewall does not open."
  echo "		protocols h1 h2"
  echo "	}"
  echo "}"
  echo
  echo "$DOMAIN {"
  [[ -z "$TLS_INTERNAL" ]] || echo "	tls internal"
  echo "	header {"
  echo "		defer"
  echo "		Strict-Transport-Security \"max-age=31536000\""
  echo "		X-Content-Type-Options \"nosniff\""
  echo "		X-Frame-Options \"DENY\""
  echo "		Referrer-Policy \"strict-origin-when-cross-origin\""
  echo "		-Server"
  echo "	}"
  echo "	# No request_body limit: container registry layers can be hundreds of MB."
  echo "	reverse_proxy gitea:3000 {"
  echo "		header_down -Server"
  echo "	}"
  echo "	log {"
  echo "		output stdout"
  echo "	}"
  echo "}"
} > "$OUT/Caddyfile"

# --- compose.yaml ----------------------------------------------------------------------
{
  cat <<EOF
# Generated by agent/render-services.sh from kit.env - do not edit, re-run setup.sh.
# Root Docker, project "adk". Gitea has no host port: only Caddy reaches it on this network.
name: adk

services:
  gitea:
    image: $ADK_GITEA_IMAGE
    restart: unless-stopped
    security_opt:
      - no-new-privileges:true
    environment:
      USER_UID: "$GITEA_UID"
      USER_GID: "$GITEA_GID"
      GITEA__database__DB_TYPE: "sqlite3"
      GITEA__database__PATH: "/data/gitea/gitea.db"
      GITEA__server__DOMAIN: "$DOMAIN"
      GITEA__server__ROOT_URL: "https://$DOMAIN/"
      GITEA__server__HTTP_PORT: "3000"
      GITEA__server__DISABLE_SSH: "true"
      GITEA__server__START_SSH_SERVER: "false"
      GITEA__server__LFS_START_SERVER: "true"
      GITEA__server__LFS_JWT_SECRET__FILE: "/run/secrets/gitea_lfs_jwt_secret"
      GITEA__security__INSTALL_LOCK: "true"
      GITEA__security__SECRET_KEY__FILE: "/run/secrets/gitea_secret_key"
      GITEA__security__INTERNAL_TOKEN__FILE: "/run/secrets/gitea_internal_token"
      GITEA__oauth2__JWT_SECRET__FILE: "/run/secrets/gitea_jwt_secret"
      GITEA__service__DISABLE_REGISTRATION: "true"
      GITEA__service__REQUIRE_SIGNIN_VIEW: "true"
      GITEA__service__DEFAULT_KEEP_EMAIL_PRIVATE: "true"
      GITEA__service__DEFAULT_ALLOW_CREATE_ORGANIZATION: "false"
      GITEA__openid__ENABLE_OPENID_SIGNIN: "false"
      GITEA__openid__ENABLE_OPENID_SIGNUP: "false"
      GITEA__repository__DEFAULT_PRIVATE: "private"
      GITEA__session__COOKIE_SECURE: "true"
      GITEA__security__X_FRAME_OPTIONS: "DENY"
      GITEA__actions__ENABLED: "true"
      GITEA__packages__ENABLED: "true"
      GITEA__mailer__ENABLED: "false"
    secrets:
      - gitea_secret_key
      - gitea_internal_token
      - gitea_jwt_secret
      - gitea_lfs_jwt_secret
    volumes:
      - $GITEA_DATA:/data
    healthcheck:
      test: ["CMD", "curl", "-fsS", "-o", "/dev/null", "http://127.0.0.1:3000/api/healthz"]
      interval: 30s
      timeout: 5s
      retries: 3
      start_period: 60s

  caddy:
    image: $caddy_image
EOF
  if [[ "$caddy_build" == true ]]; then
    cat <<EOF
    build:
      context: ./caddy
    env_file:
      - $SECRETS_DIR/caddy.env
EOF
  fi
  cat <<EOF
    restart: unless-stopped
    depends_on:
      - gitea
    cap_drop:
      - ALL
    cap_add:
      - NET_BIND_SERVICE
    security_opt:
      - no-new-privileges:true
    ports:
EOF
  [[ "$MODE" == http01 ]] && echo '      - "80:80/tcp"'
  cat <<EOF
      - "443:443/tcp"
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy_data:/data
      - caddy_config:/config

volumes:
  caddy_data:
  caddy_config:

secrets:
  gitea_secret_key:
    file: $SECRETS_DIR/gitea-secret-key
  gitea_internal_token:
    file: $SECRETS_DIR/gitea-internal-token
  gitea_jwt_secret:
    file: $SECRETS_DIR/gitea-jwt-secret
  gitea_lfs_jwt_secret:
    file: $SECRETS_DIR/gitea-lfs-jwt-secret
EOF
} > "$OUT/compose.yaml"

# --- runner.yaml -----------------------------------------------------------------------
options=""
[[ -z "$ADD_HOST" ]] || options="--add-host=$DOMAIN:$ADD_HOST"
volumes="[]"
if [[ -n "$TLS_INTERNAL" ]]; then
  volumes='["/etc/ssl/certs/ca-certificates.crt:/etc/ssl/certs/ca-certificates.crt:ro"]'
fi
cat > "$OUT/runner.yaml" <<EOF
# Generated by agent/render-services.sh from kit.env - do not edit, re-run setup.sh.
# Gitea runner as user ci (adk-act-runner.service). Jobs run in containers of ci's ROOTLESS
# Docker; docker_host "" mounts that socket into jobs so they can docker build/push. A job
# therefore has the rights of user ci (no root, no root Docker socket, no other homes).
log:
  level: info
runner:
  file: $RUNNER_STATE/.runner
  capacity: 2
  timeout: 3h
  insecure: false
  fetch_timeout: 5s
  fetch_interval: 2s
  labels:
    - "ubuntu-latest:docker://$ADK_RUNNER_JOB_IMAGE"
cache:
  # Off: the built-in cache server listens without authentication on the host.
  enabled: false
container:
  network: ""
  privileged: false
  options: "$options"
  valid_volumes: []
  volumes: $volumes
  docker_host: ""
  require_docker: true
  docker_timeout: 120s
  force_pull: false
host:
  workdir_parent: $RUNNER_STATE/host
EOF
