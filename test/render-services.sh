#!/usr/bin/env bash
# Render the Caddy service of the TEST VM from kit.env into a directory:
#
#   compose.yaml      Caddy only (root Docker, project "adk-test", host network: it proxies to
#                     the apps' ports on 127.0.0.1)
#   Caddyfile         TLS (ACME DNS-01: ONE wildcard certificate *.TEST_DOMAIN; HTTP-01: one
#                     certificate per site), security headers, sites from sites/*.caddy
#                     (written by test/deploy.sh), admin API only on a unix socket inside the
#                     container (deploy.sh reloads through it; nothing listens on :2019)
#   caddy/Dockerfile  only for ACME_MODE=dns01: Caddy with the pinned caddy-dns module
#
# Usage: test/render-services.sh --config FILE --out DIR
#
# Lab/test override (environment only, not a kit.env key): ADK_TLS_INTERNAL=1 - Caddy's
# internal CA instead of ACME.
# Exit codes: 0 = rendered, 1 = invalid kit.env / unsupported value, 2 = usage.
set -euo pipefail
export LC_ALL=C

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
# shellcheck source-path=SCRIPTDIR source=../scripts/lib/config.sh
source "$ROOT/scripts/lib/config.sh"
# shellcheck source-path=SCRIPTDIR source=../agent/lib/versions.sh
source "$ROOT/agent/lib/versions.sh"
# shellcheck source-path=SCRIPTDIR source=../agent/lib/caddy.sh
source "$ROOT/agent/lib/caddy.sh"

SECRETS_DIR=/opt/adk/secrets
ADMIN_SOCKET=unix//run/caddy/admin.sock

usage() { echo "usage: $0 --config FILE --out DIR" >&2; exit 2; }

CONFIG="" OUT=""
while (($#)); do
  case "$1" in
    --config) (($# >= 2)) || usage; CONFIG="$2"; shift 2 ;;
    --out) (($# >= 2)) || usage; OUT="$2"; shift 2 ;;
    *) usage ;;
  esac
done
[[ -n "$CONFIG" && -n "$OUT" ]] || usage
[[ -d "$OUT" ]] || { echo "ERROR: output directory $OUT does not exist" >&2; exit 2; }
TLS_INTERNAL="${ADK_TLS_INTERNAL:-}"
[[ -z "$TLS_INTERNAL" || "$TLS_INTERNAL" == 1 ]] || { echo "ERROR: ADK_TLS_INTERNAL must be 1 or empty" >&2; exit 2; }

if ! check_out="$("$ROOT/scripts/check-config.sh" "$CONFIG")"; then
  printf '%s\n' "$check_out" >&2
  exit 1
fi
load_config "$CONFIG"
DOMAIN="${CFG[TEST_DOMAIN]}" MODE="${CFG[ACME_MODE]}" PROVIDER="${CFG[DNS_PROVIDER]}" EMAIL="${CFG[ACME_EMAIL]}"

# --- Caddy image -----------------------------------------------------------------------
if [[ "$MODE" == dns01 ]]; then
  dockerfile="$(adk_caddy_dockerfile test/render-services.sh "$PROVIDER")" || exit 1
  mkdir -p "$OUT/caddy"
  printf '%s\n' "$dockerfile" > "$OUT/caddy/Dockerfile"
else
  rm -rf "$OUT/caddy"
fi
caddy_image="$(adk_caddy_image test/render-services.sh "$MODE" "$PROVIDER")"

# --- Caddyfile -------------------------------------------------------------------------
{
  echo "# Generated by test/render-services.sh from kit.env - do not edit, re-run test/setup.sh."
  adk_caddy_options "Admin API only on a unix socket inside this container (test/deploy.sh reloads)." \
    "$ADMIN_SOCKET" "$EMAIL" "$MODE" "$PROVIDER" "$TLS_INTERNAL"
  echo
  echo "(adk_site) {"
  [[ -z "$TLS_INTERNAL" ]] || echo "	tls internal"
  adk_caddy_headers
  echo "	log {"
  echo "		output stdout"
  echo "	}"
  echo "}"
  echo
  if [[ "$MODE" == dns01 ]]; then
    echo "# One wildcard certificate (DNS-01) for all projects; deploy.sh adds one handler per"
    echo "# project in sites/. Unknown names are refused."
    echo "*.$DOMAIN {"
    echo "	import adk_site"
    echo "	import /etc/caddy/sites/*.caddy"
    echo "	handle {"
    echo "		abort"
    echo "	}"
    echo "}"
  else
    echo "# One site per project (HTTP-01 certificate each), written by deploy.sh."
    echo "import /etc/caddy/sites/*.caddy"
  fi
} > "$OUT/Caddyfile"

# --- compose.yaml ----------------------------------------------------------------------
{
  cat <<EOF
# Generated by test/render-services.sh from kit.env - do not edit, re-run test/setup.sh.
# Root Docker, project "adk-test": Caddy on the host network (it proxies to the apps on
# 127.0.0.1:<http_port>, see deploy/adk.json of each project).
name: adk-test

services:
  caddy:
    image: $caddy_image
EOF
  if [[ "$MODE" == dns01 ]]; then
    cat <<EOF
    build:
      context: ./caddy
    env_file:
      - $SECRETS_DIR/caddy.env
EOF
  fi
  cat <<EOF
    restart: unless-stopped
    network_mode: host
    cap_drop:
      - ALL
    cap_add:
      - NET_BIND_SERVICE
    security_opt:
      - no-new-privileges:true
    tmpfs:
      - /run/caddy:mode=0700
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - ./sites:/etc/caddy/sites:ro
      - caddy_data:/data
      - caddy_config:/config

volumes:
  caddy_data:
  caddy_config:
EOF
} > "$OUT/compose.yaml"
